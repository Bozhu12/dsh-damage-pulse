/**
 * Generate vendor-primitives.js: the minimal subset of
 * @deepseek-ai/dsh-client-ui-primitives that this plugin's client actually
 * imports (Button, Input, Menu, Pill, Modal) plus its dependency closure.
 *
 * Why: the published package ships one prebundled lib/index.js whose module
 * scope statically reaches the whole markdown/shiki/katex stack. Importing
 * even one name from that barrel drags ~2.5MB of dead code into client.js —
 * rolldown cannot tree-shake it. The closure here is computed with the
 * TypeScript checker, so shadowed locals do not cause false pulls.
 *
 * Regenerate whenever the primitives devDependency version changes:
 *
 *   node scripts/vendor-primitives.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import ts from 'typescript'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const BARREL = join(ROOT, 'node_modules/@deepseek-ai/dsh-client-ui-primitives/lib/index.js')
const OUT = join(ROOT, 'packages/client/ui-token-monitor/src/client/vendor-primitives.js')
const KEEP_EXPORTS = ['Button', 'Input', 'Menu', 'Pill', 'Modal']

const primitivesPkg = JSON.parse(readFileSync(join(ROOT, 'node_modules/@deepseek-ai/dsh-client-ui-primitives/package.json'), 'utf8'))
const PRIMITIVES_VERSION = primitivesPkg.version
const HEADER = `/* Generated by scripts/vendor-primitives.mjs from
 * @deepseek-ai/dsh-client-ui-primitives@${PRIMITIVES_VERSION} — DO NOT EDIT.
 * Regenerate with: node scripts/vendor-primitives.mjs [--check] */
`
const sourceText = readFileSync(BARREL, 'utf8')
const program = ts.createProgram([BARREL], { allowJs: true, target: ts.ScriptTarget.ES2022 })
const checker = program.getTypeChecker()
// The checker only binds nodes from the program's own parsed instance.
const sf = program.getSourceFile(BARREL)

const statements = sf.statements
/** Top-level statement that declares each exported binding. */
function declarationStatementFor(name) {
  for (const st of statements) {
    if (ts.isVariableStatement(st)) {
      for (const d of st.declarationList.declarations) {
        for (const id of collectBindingNames(d.name)) {
          if (id.text === name) return st
        }
      }
    } else if ((ts.isFunctionDeclaration(st) || ts.isClassDeclaration(st)) && st.name?.text === name) return st
  }
  return null
}
function collectBindingNames(node, out = []) {
  if (ts.isIdentifier(node)) out.push(node)
  else ts.forEachChild(node, (n) => collectBindingNames(n, out))
  return out
}

const keptStatements = new Set()
const queue = []
for (const name of KEEP_EXPORTS) {
  const st = declarationStatementFor(name)
  if (!st) { console.error(`export name not found: ${name}`); process.exit(1) }
  queue.push(st)
}
/** True if this identifier resolves to a top-level declaration (not a local/shadowed binding). */
function topLevelOwnerOf(id) {
  const symbol = checker.getSymbolAtLocation(id)
  if (!symbol) return null
  for (const decl of symbol.declarations ?? []) {
    let node = decl
    while (node && node.parent !== sf) node = node.parent
    if (node && statements.includes(node)) return node
  }
  return null
}
function visit(node) {
  if (ts.isIdentifier(node) || ts.isPrivateIdentifier(node)) {
    const owner = topLevelOwnerOf(node)
    if (owner && !keptStatements.has(owner)) { keptStatements.add(owner); queue.push(owner) }
  }
  ts.forEachChild(node, visit)
}
while (queue.length) {
  const st = queue.pop()
  keptStatements.add(st)
  visit(st)
}

// --- Emit --------------------------------------------------------------------
const vendorDir = dirname(OUT)
const out = []
for (const st of statements) {
  if (!keptStatements.has(st)) continue
  if (ts.isImportDeclaration(st)) {
    const spec = st.moduleSpecifier.text
    const line = sourceText.slice(st.getStart(sf), st.getEnd())
    if (spec.startsWith('.') || spec.startsWith('/')) {
      const abs = resolve(dirname(BARREL), spec)
      const rel = relative(vendorDir, abs).replaceAll('\\', '/')
      const src2 = rel.startsWith('.') ? rel : './' + rel
      out.push(line.replace(spec, src2))
    } else {
      out.push(line)
    }
  } else if (ts.isExportDeclaration(st)) {
    continue // replaced by our own export list below
  } else {
    // Track //#region banner comments that immediately precede kept statements.
    const start = st.getStart(sf)
    out.push(sourceText.slice(start, st.getEnd()))
  }
}
out.push('')
out.push(`export { ${KEEP_EXPORTS.join(', ')} };`)
out.push('')
const outputText = HEADER + out.join('\n')

if (process.argv.includes('--check')) {
  const current = readFileSync(OUT, 'utf8')
  const currentVersion = current.match(/@deepseek-ai\/dsh-client-ui-primitives@([^\s*]+)\u0020\u2014/)?.[1]
  if (current !== outputText) {
    console.error(`vendor-primitives.js is stale (installed primitives: ${PRIMITIVES_VERSION}, file: ${currentVersion ?? 'unknown'}).`)
    console.error('Regenerate with: node scripts/vendor-primitives.mjs')
    process.exit(1)
  }
  console.log(`vendor-primitives.js matches primitives@${PRIMITIVES_VERSION}`)
  process.exit(0)
}
writeFileSync(OUT, outputText)
const dropped = ['shiki', 'katex', 'micromark', 'mdast', 'anser', 'diff', 'simple-icons']
const outText = out.join('\n')
console.log(`vendor written: ${OUT} (${(outText.length / 1e3).toFixed(0)}KB)`)
console.log(`statements kept: ${keptStatements.size}/${statements.length}`)
for (const d of dropped) console.log(`  ${d}: ${outText.includes(d) ? 'STILL PRESENT' : 'gone'}`)
